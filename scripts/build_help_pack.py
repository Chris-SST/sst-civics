"""Build the reference material of the help chat (D-066) from the guide site and the fact
checklists, so the chat answers from our own reviewed text and not from the model's memory.

    python scripts/build_help_pack.py            write content/help/
    python scripts/build_help_pack.py --check    exit 1 if content/help/ is out of date

Writes content/help/guide.md (the English guide pages and FAQ, with their German page
addresses) and content/help/facts-<canton>.md (each scope fact in German and English, grouped
by topic). Links are written as `{{GUIDE_URL}}/en/...`; the app fills in the guide site's
address (GUIDE_BASE_URL) when it loads the files. The files are generated: edit the guide
pages or the scope files, then run this script."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
GUIDE = ROOT / "site" / "src" / "content" / "guide"
FAQ = ROOT / "site" / "src" / "content" / "faq"
PAGES_MJS = ROOT / "site" / "src" / "i18n" / "pages.mjs"
CONTENT = ROOT / "content"
OUT = CONTENT / "help"

HEADER = "<!-- Generated by scripts/build_help_pack.py from {src}. Do not edit by hand. -->\n\n"


def _slugs() -> dict[str, dict[str, str]]:
    """The SLUGS table of pages.mjs: page key -> {lang or "other": slug}."""
    text = PAGES_MJS.read_text(encoding="utf-8")
    block = text[text.index("export const SLUGS") :]
    block = block[: block.index("};")]
    table: dict[str, dict[str, str]] = {}
    for key, body in re.findall(r"^\s*(\w+):\s*\{([^}]*)\}", block, re.M):
        table[key] = dict(re.findall(r"(\w+):\s*\"([^\"]+)\"", body))
    return table


def _home_keys() -> list[str]:
    text = PAGES_MJS.read_text(encoding="utf-8")
    m = re.search(r"export const HOME_KEYS = \[([^\]]*)\]", text)
    return re.findall(r"\"([^\"]+)\"", m.group(1)) if m else []


def _split(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}, text
    _, front, body = text.split("---", 2)
    return yaml.safe_load(front) or {}, body.strip()


def _absolute_links(body: str) -> str:
    """`](/en/fees/)` -> `]({{GUIDE_URL}}/en/fees/)`, so a link works from the app too."""
    return re.sub(r"\]\((/[a-z]{2}/)", r"]({{GUIDE_URL}}\1", body)


def build_guide() -> str:
    slugs = _slugs()
    key_of = {(row.get("en") or row["other"]): key for key, row in slugs.items()}
    order = {k: i for i, k in enumerate(_home_keys())}
    pages = []
    for path in sorted((GUIDE / "en").glob("*.md")):
        front, body = _split(path)
        if front.get("draft"):
            continue
        slug = front.get("slug") or path.stem
        key = key_of.get(slug, slug)
        de = slugs.get(key, {}).get("de") or slugs.get(key, {}).get("other") or slug
        pages.append((order.get(key, 99), slug, de, front, body))
    pages.sort(key=lambda p: (p[0], p[1]))

    out = [HEADER.format(src="site/src/content (guide/en, faq/en)")]
    out.append("# Viapunt guide (English)\n")
    out.append(
        "The pages of the Viapunt naturalisation guide for the canton of Zurich, as published. "
        "Each page also exists in German and, as drafts, in six more languages.\n"
    )
    for _, slug, de, front, body in pages:
        out.append(f"\n## Page: {front.get('title', slug)}\n")
        out.append(f"English: {{{{GUIDE_URL}}}}/en/{slug}/  ")
        out.append(f"German: {{{{GUIDE_URL}}}}/de/{de}/  ")
        if front.get("lastChecked"):
            out.append(f"Last checked: {front['lastChecked']}\n")
        out.append("\n" + _absolute_links(body) + "\n")
        sources = front.get("sources") or []
        if sources:
            out.append("\nOfficial sources of this page:\n")
            out.extend(f"- {s.get('title', '')}: {s['url']}" for s in sources if s.get("url"))
            out.append("")

    faq_de = slugs.get("faq", {}).get("de", "faq")
    out.append("\n## Page: Frequently asked questions\n")
    out.append("English: {{GUIDE_URL}}/en/faq/  ")
    out.append(f"German: {{{{GUIDE_URL}}}}/de/{faq_de}/\n")
    items = []
    for path in sorted((FAQ / "en").glob("*.md")):
        front, body = _split(path)
        items.append((front.get("order", 99), front.get("question", path.stem), body))
    for _, question, body in sorted(items):
        out.append(f"\n### {question}\n\n{_absolute_links(body)}\n")
    return _tidy(out)


def _tidy(lines: list[str]) -> str:
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).rstrip() + "\n"


def build_facts(scope_path: Path) -> tuple[str, str]:
    scope = yaml.safe_load(scope_path.read_text(encoding="utf-8"))
    canton = scope["canton"]
    topics_path = CONTENT / "topics" / f"{canton}.yaml"
    names: dict[str, str] = {}
    order: dict[str, int] = {}
    if topics_path.is_file():
        topics = yaml.safe_load(topics_path.read_text(encoding="utf-8")).get("topics", [])
        for i, t in enumerate(topics):
            names[t["code"]] = f"{t.get('name_en', t['code'])} ({t.get('name_de', '')})"
            order[t["code"]] = i
    groups: dict[str, list[dict]] = {}
    for fact in scope["facts"]:
        groups.setdefault(fact["topic"], []).append(fact)

    out = [HEADER.format(src=f"content/scope/{canton}.yaml")]
    out.append(f"# What the knowledge test of the canton {canton.upper()} covers\n")
    out.append(
        "One line per fact the official question catalogue asks about, in our own words, in "
        "German (the language of the test) and English. Grouped by study topic.\n"
    )
    for code in sorted(groups, key=lambda c: (order.get(c, 999), c)):
        out.append(f"\n## {names.get(code, code)}\n")
        for f in groups[code]:
            out.append(f"- {f['fact_de'].strip()} / {f['fact_en'].strip()}")
    return canton, _tidy(out)


def build() -> dict[Path, str]:
    files = {OUT / "guide.md": build_guide()}
    for scope_path in sorted((CONTENT / "scope").glob("*.yaml")):
        canton, text = build_facts(scope_path)
        files[OUT / f"facts-{canton}.md"] = text
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if content/help is stale")
    args = parser.parse_args()
    files = build()
    stale = [
        p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run scripts/build_help_pack.py)")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in files.items():
        p.write_bytes(text.encode("utf-8"))
        print(f"wrote {p.relative_to(ROOT)} ({len(text):,} characters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
